const assert = require('node:assert/strict');
const { Demo, stages } = require('../model.js');
const demo = new Demo();
const original = JSON.stringify(demo.state);

assert.equal(stages.length, 9);
assert.deepEqual(demo.metrics(), { inShop: 3, ready: 1, pending: 2, appointments: 1, receivable: 900 });
assert.equal(demo.visits('ft150'), 2);
assert.equal(demo.balance(demo.order('TF-1042')), 380);
assert.equal(demo.finish('TF-1042'), false, 'Cannot complete a diagnostic without repair');
assert.equal(demo.advance('TF-1044'), false, 'Missing part blocks repair completion');
assert.equal(demo.advance('TF-1043'), true, 'Paid ready order may be delivered');
assert.equal(demo.metrics().inShop, 2);
demo.reset();

for (let i = 0; i < 6; i++) demo.chatNext();
for (let i = 0; i < 3; i++) demo.ensureAppointment();
assert.equal(demo.state.chatStep, 4);
const appointment = demo.state.appointments.filter(a => a.id === 'carlos-whatsapp');
assert.equal(appointment.length, 1, 'Chat and presentation share one appointment');
assert.equal(appointment[0].customerId, demo.bike('ft150').customerId);
assert.equal(appointment[0].time, '11:00');
assert.equal(demo.metrics().appointments, 2);
demo.prepareRepair();
assert.equal(demo.order('TF-1042').stage, 5);
assert.equal(demo.order('TF-1042').authorized, true);
assert.equal(demo.order('TF-1042').mechanicId, 'miguel');
demo.observe('TF-1042'); demo.observe('TF-1042');
assert.equal(demo.order('TF-1042').observations.length, 1);
assert.equal(demo.finish('TF-1042'), true);
assert.equal(demo.order('TF-1042').stage, 7);
assert.equal(demo.metrics().ready, 2);
assert.equal(demo.visits('ft150'), 3);
assert.equal(demo.bike('ft150').nextReview, false);
assert.equal(demo.history('ft150')[0].orderId, 'TF-1042');
assert.equal(demo.state.notifications.filter(n => n.orderId === 'TF-1042').length, 1);
assert.equal(demo.state.inventory.find(i => i.id === 'oil').stock, 11);
demo.finish('TF-1042'); demo.prepareRepair();
assert.equal(demo.visits('ft150'), 3, 'Story revisit cannot duplicate visits or consume parts twice');
assert.equal(demo.state.inventory.find(i => i.id === 'oil').stock, 11);
assert.equal(demo.advance('TF-1042'), false, 'Delivery requires settling the example balance');
assert.equal(demo.pay('TF-1042', 'Invalid'), false);
assert.equal(demo.pay('TF-1042', 'Tarjeta'), true);
assert.equal(demo.balance(demo.order('TF-1042')), 0);
assert.equal(demo.pay('TF-1042', 'Tarjeta'), false, 'Payment cannot be recorded twice');
assert.equal(demo.advance('TF-1042'), true);
assert.equal(demo.metrics().receivable, 520);
assert.equal(demo.assign('TF-1042', 'owner'), false, 'Only mechanic profiles are assignable');
assert.equal(demo.assign('TF-1042', 'elena'), true);
assert.equal(demo.assign('missing', 'miguel'), false);

assert.equal(demo.updateKm(18000), false);
assert.equal(demo.updateKm(18500.5), false);
assert.equal(demo.updateKm(1000000), false);
assert.equal(demo.updateKm(18500), true);
assert.equal(demo.bike('ft150').km, 18500);
const count = demo.visits('ft150');
assert.equal(demo.personalService('<script>'), false);
assert.equal(demo.personalService('Limpieza y lubricación'), true);
assert.equal(demo.visits('ft150'), count, 'Personal entries are never verified or eligible');
const personal = demo.history('ft150').find(s => !s.verified && s.date === demo.state.date);
assert.equal(personal.km, 18500);
assert.equal(personal.eligible, false);

const order = demo.newOrder('yamaha');
assert.deepEqual(order, { id: 'TF-1045', created: true });
assert.deepEqual(demo.newOrder('yamaha'), { id: 'TF-1045', created: false });
assert.equal(demo.newOrder('unknown'), null);
assert.equal(demo.receivePart('TF-1044'), true);
assert.equal(demo.receivePart('TF-1044'), false, 'Part receipt is idempotent');
assert.equal(demo.finish('TF-1044'), true);
demo.reset();
assert.equal(JSON.stringify(demo.state), original, 'Reset restores the entire scenario');
const other = new Demo(); other.bike('ft150').km = 20000;
assert.equal(demo.bike('ft150').km, 18450, 'Fixtures are not shared between sessions');
console.log('Torre Fuerte model: coherent lifecycle, idempotent story, cash, history, inventory and reset passed.');
